"""Collect the runs in results/ (written by run_queue.py jobs) into the paper's tables.

Usage: python summarize.py > results/summary.md   (needs scikit-learn for AUC)

For every <model>_<full|noit>_<setting>.json: usable predictions, MAE / RMSE (and on the leak-free test set when
<name>_noleak.json exists), ROC-AUC from the predicted values (rating datasets: positive = rating >= 4 as in
Kang et al., and >= 3 as written in main.tex; MIND: click), and split / sliding-window conformal prediction on
the nonconformity score |r - r_hat| (same procedure as recompute.py: 30% calibration and 1000 random splits;
window of the 100 previous scores; widths clipped to the answer scale).
"""
import glob
import json
import os
import random
import sys

from sklearn.metrics import roc_auc_score

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from recompute import CAL_RATIO, EPSILONS, N_SPLITS, WINDOW, cp_quantile

HERE = os.path.dirname(os.path.abspath(__file__))


def load(path):
    r = json.load(open(path))["runs"]["full"]
    lo, hi = (0, 1) if "MIND" in os.path.basename(path) else (1, 5)
    pairs = [(t, p) for t, p in zip(r["truth"], r["pred"])
             if t is not None and p is not None and lo <= t <= hi and lo <= p <= hi]
    return pairs, len(r["truth"]), (lo, hi)


def mae_rmse(pairs):
    n = len(pairs)
    return sum(abs(t - p) for t, p in pairs) / n, (sum((t - p) ** 2 for t, p in pairs) / n) ** 0.5


def auc(pairs, threshold):
    y = [int(t >= threshold) for t, _ in pairs]
    return roc_auc_score(y, [p for _, p in pairs]) if 0 < sum(y) < len(y) else None


def width(pred, tau, scale):
    return min(scale[1], pred + tau) - max(scale[0], pred - tau)


def split_cp(pairs, eps, scale, rng):
    idx, cov, wid = list(range(len(pairs))), 0.0, 0.0
    n_cal = int(len(pairs) * CAL_RATIO)
    for _ in range(N_SPLITS):
        rng.shuffle(idx)
        cal, test = idx[:n_cal], idx[n_cal:]
        tau = cp_quantile([abs(pairs[i][0] - pairs[i][1]) for i in cal], eps)
        cov += sum(abs(pairs[i][0] - pairs[i][1]) <= tau for i in test) / len(test)
        wid += sum(width(pairs[i][1], tau, scale) for i in test) / len(test)
    return wid / N_SPLITS, 100 * cov / N_SPLITS


def sliding_cp(pairs, eps, scale):
    s = [abs(t - p) for t, p in pairs]
    taus = [cp_quantile(s[i - WINDOW:i], eps) for i in range(WINDOW, len(s))]
    if not taus:
        return None, None
    w = [width(pairs[i][1], t, scale) for i, t in zip(range(WINDOW, len(s)), taus)]
    return sum(w) / len(w), 100 * sum(s[i] <= t for i, t in zip(range(WINDOW, len(s)), taus)) / len(taus)


def fmt(x, d=3):
    return "–" if x is None else f"{x:.{d}f}"


def main():
    rows, cp_rows = [], []
    for path in sorted(glob.glob(os.path.join(HERE, "results", "*.json"))):
        name = os.path.basename(path)[:-5]
        if name.endswith("_noleak"):
            continue
        model, kind, setting = name.split("_", 2)
        pairs, n, scale = load(path)
        mae, rmse = mae_rmse(pairs) if pairs else (None, None)
        nl = os.path.join(HERE, "results", name + "_noleak.json")
        nl_mae_rmse = mae_rmse(load(nl)[0]) if os.path.exists(nl) else (None, None)
        aucs = [auc(pairs, 1)] if scale == (0, 1) else [auc(pairs, 4), auc(pairs, 3)]
        rows.append((setting, model, kind, f"{len(pairs)}/{n}", fmt(mae), fmt(rmse),
                     " / ".join(fmt(a) for a in aucs), f"{fmt(nl_mae_rmse[0])} / {fmt(nl_mae_rmse[1])}"))
        if setting.endswith("-H") and kind in ("full", "clean"):
            rng = random.Random(0)
            for eps in EPSILONS:
                sw, sc = split_cp(pairs, eps, scale, rng)
                lw, lc = sliding_cp(pairs, eps, scale)
                cp_rows.append((eps, setting, model, fmt(sw, 2), fmt(sc, 2), fmt(lw, 2), fmt(lc, 2)))

    print("# Runs of the missing paper experiments\n\nGenerated by `summarize.py` from `results/*.json`.\n")
    print("| Setting | Model | Variant | Usable | MAE | RMSE | AUC (>=4 / >=3; MIND: click) | Leak-free MAE / RMSE |")
    print("|---|---|---|---|---|---|---|---|")
    for r in sorted(rows):
        print("| " + " | ".join(r) + " |")
    print("\n## Conformal prediction (full CPR-LLM, -H settings)\n")
    print("| eps | Setting | Model | Split CP width | Split CP coverage % | Sliding CP width | Sliding CP coverage % |")
    print("|---|---|---|---|---|---|---|")
    for r in sorted(cp_rows, key=lambda r: (-r[0], r[1], r[2])):
        print("| " + " | ".join(str(x) for x in r) + " |")


if __name__ == "__main__":
    main()
